    حرف *برچسب_Buf;
    int16_t next;
    حرف *pSubtag, *p_بعدی, *p_آخرین_Good_Position;
    int32_t subtagLen;
    int32_t extlangIdx;
    icu::Local_اشاره_گر<Extension_List_مدخل> pExtension;
    حرف *p_Ext_مقدار_Subtag, *p_Ext_مقدار_Subtag_انتها;
