    ଯଦି (U_FAILURE(status)) { ଫେରନ୍ତୁ nullptr; }

    ଅକ୍ଷର *tagBuf;
    int16_t next;
    ଅକ୍ଷର *pSubtag, *pNext, *pLastGoodPosition;
    int32_t subtagLen;
    int32_t extlangIdx;
